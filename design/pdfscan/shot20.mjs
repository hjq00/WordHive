import { writeFileSync } from 'node:fs';
const list = await (await fetch('http://127.0.0.1:9450/json')).json();
const page = list.find(x => x.type === 'page');
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id=0; const pending=new Map();
ws.onmessage=({data})=>{const m=JSON.parse(data);if(m.id&&pending.has(m.id)){pending.get(m.id)(m);pending.delete(m.id);}};
const cmd=(method,params={})=>new Promise(r=>{const n=++id;pending.set(n,r);ws.send(JSON.stringify({id:n,method,params}));});
const ev=async(e)=>(await cmd('Runtime.evaluate',{expression:e,returnByValue:true,awaitPromise:true})).result?.result?.value;
await new Promise(r=>setTimeout(r,1500));
let r=await cmd('Page.captureScreenshot',{format:'png'});
writeFileSync('design/v20-ready.png',Buffer.from(r.result.data,'base64'));
const info=await ev(`(()=>{const s=getComputedStyle(document.documentElement);return {accent:s.getPropertyValue('--accent').trim(),bg:s.getPropertyValue('--bg').trim(),title:document.querySelector('.ready-title')?.textContent?.trim(),sub:document.querySelector('.ready-sub')?.textContent?.trim(),hasStart:!!document.querySelector('[data-start-study]')};})()`);
console.log('ready:',JSON.stringify(info));
await ev(`document.querySelector('#tabbar [data-tab="review"]')?.click()`);
await new Promise(r=>setTimeout(r,1500));
await ev(`window.scrollTo(0,0)`);
r=await cmd('Page.captureScreenshot',{format:'png'});
writeFileSync('design/v20-review.png',Buffer.from(r.result.data,'base64'));
const rv=await ev(`(()=>{const d=document.querySelector('.rv-donut')||document.querySelector('.rv-page svg');const seg=[...document.querySelectorAll('.rv-legend i, .legend i')].slice(0,3).map(e=>getComputedStyle(e).backgroundColor);return {rv:!!document.querySelector('.rv-page'),legendColors:seg,metrics:[...document.querySelectorAll('.rv-metric b')].map(b=>b.textContent.trim())};})()`);
console.log('review:',JSON.stringify(rv));
ws.close();
